_APOSTROPHE_VARIANTS = str.maketrans({
    '‘': "'", '’': "'", 'ʼ': "'", '´': "'", '`': "'",
})

_LOOKUP = {name.lower().strip().translate(_APOSTROPHE_VARIANTS): year for name, year in PLAYER_YEARS.items()}


def get_default_year(player_name: str) -> str | None:
    """Best-known season for a player, for auto-filling a !pick/!list that
    didn't include one. None if we have no default on record for them --
    callers should leave the year blank/unset in that case, not guess."""
    key = player_name.strip().lower().translate(_APOSTROPHE_VARIANTS)
    return _LOOKUP.get(key)
